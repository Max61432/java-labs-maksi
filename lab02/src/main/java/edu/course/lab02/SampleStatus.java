package edu.course.lab02;

/**
 * Статус наблюдения (data sample) в наборе данных.
 */
public enum SampleStatus {
    /** Наблюдение создано, но ещё не обработано. */
    NEW,
    /** Наблюдение в процессе обработки. */
    PROCESSING,
    /** Наблюдение готово к использованию. */
    READY,
    /** Наблюдение отклонено. */
    REJECTED
}